-- Món trong thực đơn tuần: ngày (0 = Thứ Hai … 6 = Chủ Nhật), bữa, vai trò trong mâm (UC17)
CREATE TABLE meal_plan_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  user_id uuid NOT NULL,
  day_index smallint NOT NULL,
  meal text NOT NULL,
  role text NOT NULL,
  dish_id uuid NOT NULL,
  position smallint NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (id),
  FOREIGN KEY (user_id) REFERENCES meal_plans(user_id) ON DELETE CASCADE,
  FOREIGN KEY (dish_id) REFERENCES dishes(id) ON DELETE CASCADE,
  CHECK (day_index BETWEEN 0 AND 6),
  CHECK (meal IN ('breakfast', 'lunch', 'dinner')),
  CHECK (role IN ('breakfast_main', 'breakfast_side', 'soup', 'main', 'vegetable')),
  CHECK (position BETWEEN 0 AND 9)
);
CREATE INDEX meal_plan_items_user_id_idx ON meal_plan_items (user_id, day_index, meal, position);
CREATE INDEX meal_plan_items_dish_id_idx ON meal_plan_items (dish_id);
COMMENT ON COLUMN meal_plan_items.role IS 'breakfast_main: món nước, cơm cháo; breakfast_side: bánh, tráng miệng; soup: canh; main: kho, chiên nướng; vegetable: xào, luộc hấp, gỏi cuốn';

