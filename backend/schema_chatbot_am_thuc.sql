-- DAT-09: avg_rating, rating_count, favorite_count denormalized trên dishes
CREATE OR REPLACE FUNCTION refresh_dish_rating() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE d uuid := COALESCE(NEW.dish_id, OLD.dish_id);
BEGIN
  UPDATE dishes SET avg_rating = COALESCE((SELECT round(avg(stars)::numeric, 2) FROM ratings WHERE dish_id = d), 0),
                    rating_count = (SELECT count(*) FROM ratings WHERE dish_id = d)
  WHERE id = d;
  IF TG_OP = 'UPDATE' AND OLD.dish_id <> NEW.dish_id THEN
    UPDATE dishes SET avg_rating = COALESCE((SELECT round(avg(stars)::numeric, 2) FROM ratings WHERE dish_id = OLD.dish_id), 0),
                      rating_count = (SELECT count(*) FROM ratings WHERE dish_id = OLD.dish_id)
    WHERE id = OLD.dish_id;
  END IF;
  RETURN NULL;
END $$;
CREATE TRIGGER ratings_refresh_dish AFTER INSERT OR UPDATE OR DELETE ON ratings
  FOR EACH ROW EXECUTE FUNCTION refresh_dish_rating();

CREATE OR REPLACE FUNCTION refresh_dish_favorites() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE d uuid := COALESCE(NEW.dish_id, OLD.dish_id);
BEGIN
  UPDATE dishes SET favorite_count = (SELECT count(*) FROM favorites WHERE dish_id = d) WHERE id = d;
  RETURN NULL;
END $$;
CREATE TRIGGER favorites_refresh_dish AFTER INSERT OR DELETE ON favorites
  FOR EACH ROW EXECUTE FUNCTION refresh_dish_favorites();

-- Chỉ công khai món đã có công thức hợp lệ (ít nhất 1 nguyên liệu và 1 bước; FR-36, FR-51).
-- Constraint trigger kiểm tra lúc COMMIT. Backend gọi qua Supabase JS nên mỗi lệnh là một transaction
-- riêng; vì vậy khi lưu công thức, backend upsert nguyên liệu/bước mới trước rồi mới xóa phần thừa,
-- để món đang hiển thị không bao giờ rỗng công thức. Khi muốn xóa hết công thức của món đang hiển thị,
-- backend phải đặt is_published = false trước (FR-51); nếu không, trigger chặn và báo lỗi RECIPE_REQUIRED.
CREATE OR REPLACE FUNCTION check_published_has_recipe() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE d uuid;
BEGIN
  IF TG_TABLE_NAME = 'dishes' THEN d := NEW.id; ELSE d := OLD.dish_id; END IF;
  IF EXISTS (SELECT 1 FROM dishes WHERE id = d AND is_published)
     AND (NOT EXISTS (SELECT 1 FROM recipe_steps WHERE dish_id = d)
          OR NOT EXISTS (SELECT 1 FROM dish_ingredients WHERE dish_id = d)) THEN
    RAISE EXCEPTION 'RECIPE_REQUIRED: món % chưa có công thức hợp lệ nên không thể hiển thị', d
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER dishes_published_has_recipe AFTER INSERT OR UPDATE OF is_published ON dishes
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_published_has_recipe();
CREATE CONSTRAINT TRIGGER recipe_steps_keep_recipe AFTER DELETE ON recipe_steps
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_published_has_recipe();
CREATE CONSTRAINT TRIGGER dish_ingredients_keep_recipe AFTER DELETE ON dish_ingredients
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_published_has_recipe();

-- Kiểm tra mã đặt lại mật khẩu (FR-16): một câu UPDATE khóa dòng nên các request song song không vượt quá
-- p_max_attempts lần sai. Mã đúng không bị tính; mã sai tăng bộ đếm; đủ p_max_attempts lần sai thì yêu cầu hết hiệu lực.
CREATE OR REPLACE FUNCTION check_password_reset_code(p_user_id uuid, p_code_hash text, p_max_attempts integer DEFAULT 5)
RETURNS TABLE (reset_id uuid, reset_user_id uuid, reset_expires_at timestamptz, matched boolean, attempts smallint)
LANGUAGE sql AS $$
  UPDATE password_reset_tokens t
     SET failed_attempts = t.failed_attempts + CASE WHEN t.code_hash = p_code_hash THEN 0 ELSE 1 END
   WHERE t.user_id = p_user_id
     AND t.used_at IS NULL
     AND t.expires_at > now()
     AND t.failed_attempts < p_max_attempts
  RETURNING t.id, t.user_id, t.expires_at, t.code_hash = p_code_hash, t.failed_attempts;
$$;
REVOKE ALL ON FUNCTION check_password_reset_code(uuid, text, integer) FROM PUBLIC, anon, authenticated;

