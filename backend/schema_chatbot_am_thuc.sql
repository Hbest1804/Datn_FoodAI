-- Món ăn
CREATE TABLE dishes (
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  name text NOT NULL,
  slug text NOT NULL UNIQUE,
  description text,
  image_url text,
  category varchar(100) NOT NULL,
  category_normalized varchar(100) NOT NULL GENERATED ALWAYS AS (regexp_replace(lower(immutable_unaccent(btrim(category))), '\s+', ' ', 'g')) STORED,
  cook_time_minutes smallint,
  difficulty text,
  servings smallint NOT NULL,
  est_cost numeric(12,0),
  calories numeric(6,1),
  protein_g numeric(6,1),
  carbs_g numeric(6,1),
  fat_g numeric(6,1),
  avg_rating numeric(3,2) NOT NULL DEFAULT 0,
  rating_count integer NOT NULL DEFAULT 0,
  favorite_count integer NOT NULL DEFAULT 0,
  source_url text,
  is_published boolean NOT NULL DEFAULT false,
  created_by uuid,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (id),
  FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL,
  CHECK (difficulty IS NULL OR difficulty IN ('easy','medium','hard')),
  CHECK (servings > 0),
  CHECK (cook_time_minutes IS NULL OR cook_time_minutes > 0),
  CHECK (est_cost IS NULL OR est_cost >= 0),
  CHECK (calories IS NULL OR calories >= 0),
  CHECK (protein_g IS NULL OR protein_g >= 0),
  CHECK (carbs_g IS NULL OR carbs_g >= 0),
  CHECK (fat_g IS NULL OR fat_g >= 0)
);
COMMENT ON COLUMN dishes.category IS 'DAT-14';
COMMENT ON COLUMN dishes.category_normalized IS 'DAT-14: tự sinh từ category';
COMMENT ON COLUMN dishes.calories IS 'DAT-17: cho phép NULL';
