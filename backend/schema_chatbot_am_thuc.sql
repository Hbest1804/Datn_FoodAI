-- Yêu cầu đặt lại mật khẩu: một mã 6 số (nhập kèm email) và một token dài trong liên kết email
CREATE TABLE password_reset_tokens (
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL,
  token_hash text NOT NULL UNIQUE,
  code_hash text NOT NULL,
  failed_attempts smallint NOT NULL DEFAULT 0,
  expires_at timestamptz NOT NULL,
  used_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (id),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  CHECK (failed_attempts >= 0)
);
CREATE INDEX password_reset_tokens_user_id_idx ON password_reset_tokens (user_id);
COMMENT ON COLUMN password_reset_tokens.token_hash IS 'SHA-256 của token ngẫu nhiên 32 byte trong liên kết email, không lưu token gốc';
COMMENT ON COLUMN password_reset_tokens.code_hash IS 'SHA-256 của user_id:mã 6 số; mã chỉ được kiểm tra kèm email nên không cần duy nhất';
COMMENT ON COLUMN password_reset_tokens.failed_attempts IS 'Số lần nhập sai mã; đủ 5 lần thì yêu cầu bị hủy (FR-16)';
COMMENT ON COLUMN password_reset_tokens.expires_at IS 'Tạo + 15 phút (FR-14)';

