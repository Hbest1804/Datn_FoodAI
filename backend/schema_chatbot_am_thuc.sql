  needs_review boolean NOT NULL DEFAULT false,
  created_by uuid,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (id),
  FOREIGN KEY (allergen_group_id) REFERENCES allergen_groups(id) ON DELETE SET NULL,
  FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL
);
CREATE INDEX ingredients_allergen_group_id_idx ON ingredients (allergen_group_id);
COMMENT ON COLUMN ingredients.normalized_name IS 'DAT-16: tự sinh từ name (chữ thường, bỏ dấu, gộp khoảng trắng)';
