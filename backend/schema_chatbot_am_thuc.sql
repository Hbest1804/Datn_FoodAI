-- Hồ sơ cá nhân hóa của người dùng (khẩu vị, calo, ngân sách)
CREATE TABLE user_profiles (
  user_id uuid NOT NULL,
  taste_prefs jsonb NOT NULL DEFAULT '{}',
  calorie_goal numeric(6,1),
  budget_min numeric(12,0),
  budget_max numeric(12,0),
