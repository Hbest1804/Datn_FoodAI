-- 0. EXTENSIONS
CREATE EXTENSION IF NOT EXISTS pgcrypto;                 -- gen_random_uuid()
CREATE EXTENSION IF NOT EXISTS vector;                   -- pgvector: embedding 768 chiều
CREATE EXTENSION IF NOT EXISTS pg_trgm;                  -- tìm kiếm mờ, chịu lỗi chính tả
CREATE EXTENSION IF NOT EXISTS unaccent SCHEMA public;   -- bỏ dấu tiếng Việt

-- unaccent() chỉ là STABLE nên không dùng được trong cột sinh tự động hay chỉ mục biểu thức.
-- Hàm bọc IMMUTABLE dưới đây gọi unaccent với từ điển chỉ định rõ. Nếu Supabase đã cài unaccent ở
-- schema extensions thì đổi public.unaccent thành extensions.unaccent.
CREATE OR REPLACE FUNCTION immutable_unaccent(text) RETURNS text
LANGUAGE sql IMMUTABLE PARALLEL SAFE STRICT AS $$
  SELECT public.unaccent('public.unaccent'::regdictionary, $1)
$$;

-- Tài khoản người dùng và quản trị viên
CREATE TABLE users (
  id uuid NOT NULL,
  email text NOT NULL UNIQUE,
  display_name text,
  avatar_url text,
  role text NOT NULL DEFAULT 'user',
  status text NOT NULL DEFAULT 'active',
  failed_login_count smallint NOT NULL DEFAULT 0,
  locked_until timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (id),
  CHECK (role IN ('user','admin')),
  CHECK (status IN ('active','locked')),
  CHECK (failed_login_count >= 0)
);
